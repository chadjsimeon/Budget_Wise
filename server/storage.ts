export class DbStorage implements IStorage {
  constructor(private readonly db: Executor = rootDb) {}

  transaction<T>(fn: (tx: IStorage) => Promise<T>): Promise<T> {
    return rootDb.transaction((tx) => fn(new DbStorage(tx)));
  }

  // ============= USERS =============
  async getUser(id: string): Promise<User | undefined> {
    const result = await this.db.select().from(users).where(eq(users.id, id)).limit(1);
    return result[0];
  }

  async getUserByEmail(email: string): Promise<User | undefined> {
    const result = await this.db.select().from(users).where(eq(users.email, email)).limit(1);
    return result[0];
  }

  async createUser(insertUser: InsertUser): Promise<User> {
    const result = await this.db.insert(users).values(insertUser).returning();
    return result[0];
  }

  async setResetToken(email: string, tokenHash: string, expiresAt: Date): Promise<boolean> {
    const result = await this.db.update(users)
      .set({ resetToken: tokenHash, resetTokenExpiresAt: expiresAt })
      .where(eq(users.email, email))
      .returning({ id: users.id });
    return result.length > 0;
  }

  async getUserByResetToken(tokenHash: string): Promise<User | undefined> {
    const result = await this.db.select().from(users)
      .where(and(
        eq(users.resetToken, tokenHash),
        gt(users.resetTokenExpiresAt, new Date()),
      ))
      .limit(1);
    return result[0];
  }

  async resetPasswordWithToken(tokenHash: string, hashedPassword: string): Promise<string | undefined> {
    // The token check lives in the WHERE clause so two requests racing with the
    // same link can't both succeed.
    const result = await this.db.update(users)
      .set({ password: hashedPassword, resetToken: null, resetTokenExpiresAt: null })
      .where(and(
        eq(users.resetToken, tokenHash),
        gt(users.resetTokenExpiresAt, new Date()),
      ))
      .returning({ id: users.id });
    return result[0]?.id;
  }

  async deleteUserSessions(userId: string): Promise<void> {
    // The session table belongs to connect-pg-simple, which creates it on first
    // use, so it may not exist yet on a fresh database.
    const exists = await this.db.execute(sql`SELECT to_regclass('public.session') AS name`);
    if (!exists.rows[0]?.name) return;
    await this.db.execute(
      sql`DELETE FROM "session" WHERE sess->'passport'->>'user' = ${userId}`,
    );
  }

  async updatePassword(userId: string, hashedPassword: string): Promise<void> {
    await this.db.update(users)
      .set({ password: hashedPassword, resetToken: null, resetTokenExpiresAt: null })
      .where(eq(users.id, userId));
  }

  // ============= BUDGETS =============
  async createBudget(data: {
    id: string;
    userId: string;
    name: string;
    currency: string;
    currencyPlacement: "before" | "after";
    numberFormat: string;
    dateFormat: string;
  }): Promise<void> {
    await this.db.insert(budgets).values({
      id: data.id,
      userId: data.userId,
      name: data.name,
      currency: data.currency,
      currencyPlacement: data.currencyPlacement,
      numberFormat: data.numberFormat as any,
      dateFormat: data.dateFormat as any,
    });
  }

  async updateBudget(id: string, userId: string, data: Record<string, unknown>): Promise<void> {
    const dbData = pick(data, BUDGET_UPDATE_COLS);
    if (Object.keys(dbData).length === 0) return;
    await this.db.update(budgets)
      .set(dbData)
      .where(and(eq(budgets.id, id), eq(budgets.userId, userId)));
  }

  async deleteBudget(id: string, userId: string): Promise<void> {
    await this.db.delete(budgets)
      .where(and(eq(budgets.id, id), eq(budgets.userId, userId)));
  }

  // ============= ACCOUNTS =============
  async createAccount(data: {
    id: string;
    budgetId: string;
    name: string;
    type: "checking" | "savings" | "cash" | "credit" | "loan";
    balance: number;
    isActive: boolean;
    interestRate?: number;
    monthlyPayment?: number;
    originalBalance?: number;
    loanStartDate?: string;
    linkedCategoryId?: string;
  }): Promise<void> {
    await this.db.insert(accounts).values({
      id: data.id,
      budgetId: data.budgetId,
      name: data.name,
      type: data.type,
      balance: String(data.balance),
      isActive: data.isActive,
      interestRate: data.interestRate != null ? String(data.interestRate) : null,
      monthlyPayment: data.monthlyPayment != null ? String(data.monthlyPayment) : null,
      originalBalance: data.originalBalance != null ? String(data.originalBalance) : null,
      loanStartDate: data.loanStartDate ?? null,
      linkedCategoryId: data.linkedCategoryId ?? null,
    });
  }

  async updateAccount(id: string, budgetId: string, data: Record<string, unknown>): Promise<void> {
    const dbData = pick(data, ACCOUNT_UPDATE_COLS);
    if (Object.keys(dbData).length === 0) return;
    for (const key of ['balance', 'interestRate', 'monthlyPayment', 'originalBalance']) {
      if (typeof dbData[key] === 'number') {
        dbData[key] = String(dbData[key]);
      }
    }
    await this.db.update(accounts)
      .set(dbData)
      .where(and(eq(accounts.id, id), eq(accounts.budgetId, budgetId)));
  }

  async deleteAccount(id: string, budgetId: string): Promise<void> {
    await this.db.delete(accounts)
      .where(and(eq(accounts.id, id), eq(accounts.budgetId, budgetId)));
  }

  // ============= TRACKING ACCOUNTS =============
  async createTrackingAccount(data: {
    id: string;
    userId: string;
    name: string;
    type: "asset" | "liability";
    balance: number;
    notes?: string;
  }): Promise<void> {
    await this.db.insert(trackingAccounts).values({
      id: data.id,
      userId: data.userId,
      name: data.name,
      type: data.type,
      balance: String(data.balance),
      notes: data.notes ?? null,
    });
  }

  async updateTrackingAccount(id: string, userId: string, data: Record<string, unknown>): Promise<void> {
    const dbData = pick(data, TRACKING_ACCOUNT_UPDATE_COLS);
    if (Object.keys(dbData).length === 0) return;
    if (typeof dbData.balance === 'number') {
      dbData.balance = String(dbData.balance);
    }
    await this.db.update(trackingAccounts)
      .set(dbData)
      .where(and(eq(trackingAccounts.id, id), eq(trackingAccounts.userId, userId)));
  }

  async deleteTrackingAccount(id: string, userId: string): Promise<void> {
    await this.db.delete(trackingAccounts)
      .where(and(eq(trackingAccounts.id, id), eq(trackingAccounts.userId, userId)));
  }

  // ============= CATEGORY GROUPS =============
  async createCategoryGroup(data: {
    id: string;
    budgetId: string;
    name: string;
  }): Promise<void> {
    await this.db.insert(categoryGroups).values(data);
  }

  async updateCategoryGroup(id: string, budgetId: string, data: Record<string, unknown>): Promise<void> {
    const dbData = pick(data, CATEGORY_GROUP_UPDATE_COLS);
    if (Object.keys(dbData).length === 0) return;
    await this.db.update(categoryGroups)
      .set(dbData)
      .where(and(eq(categoryGroups.id, id), eq(categoryGroups.budgetId, budgetId)));
  }

  async deleteCategoryGroup(id: string, budgetId: string): Promise<void> {
    await this.db.delete(categoryGroups)
      .where(and(eq(categoryGroups.id, id), eq(categoryGroups.budgetId, budgetId)));
  }

  // ============= CATEGORIES =============
  async createCategory(data: {
    id: string;
    budgetId: string;
    groupId: string;
    name: string;
    goal?: number;
    linkedAccountId?: string;
  }): Promise<void> {
    await this.db.insert(categories).values({
      id: data.id,
      budgetId: data.budgetId,
      groupId: data.groupId,
      name: data.name,
      goal: data.goal != null ? String(data.goal) : null,
      linkedAccountId: data.linkedAccountId ?? null,
    });
  }

  async updateCategory(id: string, budgetId: string, data: Record<string, unknown>): Promise<void> {
    const dbData = pick(data, CATEGORY_UPDATE_COLS);
    if (Object.keys(dbData).length === 0) return;
    if (typeof dbData.goal === 'number') {
      dbData.goal = String(dbData.goal);
    }
    await this.db.update(categories)
      .set(dbData)
      .where(and(eq(categories.id, id), eq(categories.budgetId, budgetId)));
  }

  async deleteCategory(id: string, budgetId: string): Promise<void> {
    await this.db.delete(categories)
      .where(and(eq(categories.id, id), eq(categories.budgetId, budgetId)));
  }

  // ============= TRANSACTIONS =============
  async createTransaction(data: {
    id: string;
    budgetId: string;
    date: string;
    payee: string;
    categoryId?: string;
    accountId: string;
    amount: number;
    memo?: string;
    cleared: boolean;
    autoGeneratedById?: string;
  }): Promise<BalanceChange> {
    const [row] = await this.db.insert(transactions).values({
      id: data.id,
      budgetId: data.budgetId,
      date: data.date,
      payee: data.payee,
      categoryId: data.categoryId ?? null,
      accountId: data.accountId,
      amount: String(data.amount),
      memo: data.memo ?? null,
      cleared: data.cleared,
      autoGeneratedById: data.autoGeneratedById ?? null,
    }).returning({ accountId: transactions.accountId, amount: transactions.amount });
    return { accountId: row.accountId, cents: toCents(row.amount) };
  }

  async updateTransaction(id: string, budgetId: string, data: Record<string, unknown>): Promise<BalanceChange[]> {
    const dbData = pick(data, TRANSACTION_UPDATE_COLS);
    if (Object.keys(dbData).length === 0) return [];
    if (typeof dbData.amount === 'number') {
      dbData.amount = String(dbData.amount);
    }
    dbData.updatedAt = new Date();
    const where = and(eq(transactions.id, id), eq(transactions.budgetId, budgetId));
    // Lock the row so the amount being reversed is the one being replaced.
    const [before] = await this.db
      .select({ accountId: transactions.accountId, amount: transactions.amount })
      .from(transactions)
      .where(where)
      .for("update");
    if (!before) return [];
    const [after] = await this.db.update(transactions)
      .set(dbData)
      .where(where)
      .returning({ accountId: transactions.accountId, amount: transactions.amount });
    return [
      { accountId: before.accountId, cents: -toCents(before.amount) },
      { accountId: after.accountId, cents: toCents(after.amount) },
    ];
  }

  async deleteTransaction(id: string, budgetId: string): Promise<BalanceChange[]> {
    const deleted = await this.db.delete(transactions)
      .where(and(eq(transactions.id, id), eq(transactions.budgetId, budgetId)))
      .returning({ accountId: transactions.accountId, amount: transactions.amount });
    return deleted.map((row) => ({ accountId: row.accountId, cents: -toCents(row.amount) }));
  }

  async applyBalanceChanges(budgetId: string, changes: BalanceChange[]): Promise<void> {
    // Net the changes per account first: the loan rule below looks at where a
    // balance ends up after the whole operation, not at each step along the way.
    const net = new Map<string, number>();
    for (const { accountId, cents } of changes) {
      net.set(accountId, (net.get(accountId) ?? 0) + cents);
    }

    for (const [accountId, cents] of Array.from(net)) {
      if (cents === 0) continue;
      const where = and(eq(accounts.id, accountId), eq(accounts.budgetId, budgetId));
      // Relative update, so concurrent writers add up instead of overwriting.
      const [account] = await this.db.update(accounts)
        .set({ balance: sql`${accounts.balance} + ${(cents / 100).toFixed(2)}::numeric` })
        .where(where)
        .returning({ type: accounts.type, balance: accounts.balance, isActive: accounts.isActive });
      if (!account || account.type !== "loan") continue;

      // Loan rule — keep in step with applyBalanceDelta in client/src/lib/store.ts:
      // a loan paid up to (or past) zero is closed at zero; one that owes is open.
      const balance = toCents(account.balance);
      if (balance >= 0) {
        if (balance !== 0 || account.isActive) {
          await this.db.update(accounts).set({ balance: "0", isActive: false }).where(where);
        }
      } else if (!account.isActive) {
        await this.db.update(accounts).set({ isActive: true }).where(where);
      }
    }
  }

  // ============= MONTHLY ASSIGNMENTS =============
  async upsertAssignment(data: {
    budgetId: string;
    monthKey: string;
    categoryId: string;
    amount: number;
  }): Promise<void> {
    await this.db.insert(monthlyAssignments)
      .values({
        id: crypto.randomUUID(),
        budgetId: data.budgetId,
        monthKey: data.monthKey,
        categoryId: data.categoryId,
        amount: String(data.amount),
      })
      .onConflictDoUpdate({
        target: [monthlyAssignments.budgetId, monthlyAssignments.monthKey, monthlyAssignments.categoryId],
        set: { amount: String(data.amount) },
      });
  }

  async upsertAssignmentsBulk(assignments: Array<{
    budgetId: string;
    monthKey: string;
    categoryId: string;
    amount: number;
  }>): Promise<void> {
    await this.transaction(async (tx) => {
      for (const assignment of assignments) {
        await tx.upsertAssignment(assignment);
      }
    });
  }

  // ============= BUDGET TEMPLATES =============
  async createBudgetTemplate(data: {
    id: string;
    userId: string;
    name: string;
    isDefault: boolean;
    goals: Record<string, number>;
  }): Promise<void> {
    await this.db.insert(budgetTemplates).values({
      id: data.id,
      userId: data.userId,
      name: data.name,
      isDefault: data.isDefault,
      goals: data.goals,
    });
  }

  async updateBudgetTemplate(id: string, userId: string, data: Record<string, unknown>): Promise<void> {
    const dbData = pick(data, BUDGET_TEMPLATE_UPDATE_COLS);
    if (Object.keys(dbData).length === 0) return;
    await this.db.update(budgetTemplates)
      .set(dbData)
      .where(and(eq(budgetTemplates.id, id), eq(budgetTemplates.userId, userId)));
  }

  async deleteBudgetTemplate(id: string, userId: string): Promise<void> {
    await this.db.delete(budgetTemplates)
      .where(and(eq(budgetTemplates.id, id), eq(budgetTemplates.userId, userId)));
  }
  // ============= BILL REMINDERS =============
  async createBillReminder(data: {
    id: string;
    budgetId: string;
    name: string;
    amount: number;
    frequency: "weekly" | "biweekly" | "monthly" | "quarterly" | "yearly";
    dueDay: number;
    dueDateOverride?: string;
    categoryId?: string;
    accountId?: string;
    isActive: boolean;
    autoCreateTransaction: boolean;
    reminderDaysBefore: number;
    lastPaidDate?: string;
    notes?: string;
  }): Promise<void> {
    await this.db.insert(billReminders).values({
      id: data.id,
      budgetId: data.budgetId,
      name: data.name,
      amount: String(data.amount),
      frequency: data.frequency,
      dueDay: String(data.dueDay),
      dueDateOverride: data.dueDateOverride ?? null,
      categoryId: data.categoryId ?? null,
      accountId: data.accountId ?? null,
      isActive: data.isActive,
      autoCreateTransaction: data.autoCreateTransaction,
      reminderDaysBefore: String(data.reminderDaysBefore),
      lastPaidDate: data.lastPaidDate ?? null,
      notes: data.notes ?? null,
    });
  }

  async updateBillReminder(id: string, budgetId: string, data: Record<string, unknown>): Promise<void> {
    const dbData = pick(data, BILL_REMINDER_UPDATE_COLS);
    if (Object.keys(dbData).length === 0) return;
    if (typeof dbData.amount === 'number') dbData.amount = String(dbData.amount);
    if (typeof dbData.dueDay === 'number') dbData.dueDay = String(dbData.dueDay);
    if (typeof dbData.reminderDaysBefore === 'number') dbData.reminderDaysBefore = String(dbData.reminderDaysBefore);
    await this.db.update(billReminders)
      .set(dbData)
      .where(and(eq(billReminders.id, id), eq(billReminders.budgetId, budgetId)));
  }

  async deleteBillReminder(id: string, budgetId: string): Promise<void> {
    await this.db.delete(billReminders)
      .where(and(eq(billReminders.id, id), eq(billReminders.budgetId, budgetId)));
  }
}

export const storage = new DbStorage();
