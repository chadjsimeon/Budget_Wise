// Constant for auto-created loan category group
const DEBT_REPAYMENTS_GROUP_NAME = 'Debt Repayments';

// Name of the single shared category that tracks payments into any credit
// card account. All credit cards in a budget link to the same category —
// unlike loans, which each get their own "{account.name} Payment" category.
const CREDIT_CARD_PAYMENTS_CATEGORY_NAME = 'Credit Card Payments';

// Finds the budget's existing "Debt Repayments" category group, or returns
// a freshly-built one (not yet added to state) if none exists.
function findOrBuildDebtGroup(
  categoryGroups: CategoryGroup[],
  budgetId: string
): { debtGroupId: string; newGroup?: CategoryGroup } {
  const existing = categoryGroups.find(
    g => g.budgetId === budgetId && g.name.toLowerCase() === DEBT_REPAYMENTS_GROUP_NAME.toLowerCase()
  );
  if (existing) return { debtGroupId: existing.id };
  const newGroup: CategoryGroup = { id: crypto.randomUUID(), budgetId, name: DEBT_REPAYMENTS_GROUP_NAME };
  return { debtGroupId: newGroup.id, newGroup };
}

const toCents = (amount: number) => Math.round(amount * 100);

// Applies the net balance change of one operation to an account.
//
// The server owns account balances: it derives the same change from the
// transaction rows it stores (DbStorage.applyBalanceChanges in
// server/storage.ts) and never accepts a balance computed here. This is the
// optimistic local copy of that rule, so the two must stay in step — a loan
// that no longer owes anything is closed; a loan that owes is open. The balance
// itself is never clamped, so deleting an overpayment restores it exactly.
function applyBalanceDelta(account: Account, delta: number): Account {
  if (!delta) return account;
  // Whole cents, like the server, so float drift can't leave a loan at -0.0000001.
  const balance = (toCents(account.balance) + toCents(delta)) / 100;
  if (account.type !== 'loan') return { ...account, balance };
  return { ...account, balance, isActive: balance < 0 };
}

// Payee of the transaction created when an account's balance is edited by hand.
export const BALANCE_ADJUSTMENT_PAYEE = 'Balance Adjustment';

// Transfers made before `transferId` existed can only be recognised by the
// payee the app wrote for them.
const hasTransferPayee = (payee: string) =>
  payee.startsWith('Transfer to') || payee.startsWith('Transfer from');

export function isTransfer(t: Pick<Transaction, 'transferId' | 'payee'>): boolean {
  return !!t.transferId || hasTransferPayee(t.payee);
}

// Money that moved without being earned or spent: opening balances, transfers,
// manual balance adjustments and the auto-generated halves of a loan payment.
// Reports leave these out of income and spending.
export function isBookkeepingEntry(t: Transaction): boolean {
  return (
    !!t.isOpeningBalance ||
    t.payee === 'Opening Balance' ||
    t.payee === BALANCE_ADJUSTMENT_PAYEE ||
    !!t.autoGeneratedById ||
    isTransfer(t)
  );
}

// Removes categories and everything that hangs off them, the way the database
// does when a category row is deleted: assignments go with it, and anything
// that merely pointed at it (transactions, bill reminders, linked accounts)
// is left uncategorised.
function withoutCategories(
  state: Pick<AppState, 'categories' | 'monthlyAssignments' | 'transactions' | 'billReminders' | 'accounts'>,
  ids: ReadonlySet<string>,
) {
  const gone = (categoryId?: string) => !!categoryId && ids.has(categoryId);
  return {
    categories: state.categories.filter(c => !ids.has(c.id)),
    monthlyAssignments: Object.fromEntries(
      Object.entries(state.monthlyAssignments).map(([budgetId, months]) => [
        budgetId,
        Object.fromEntries(
          Object.entries(months).map(([monthKey, assignments]) => [
            monthKey,
            Object.fromEntries(Object.entries(assignments).filter(([categoryId]) => !ids.has(categoryId))),
          ])
        ),
      ])
    ) as MonthlyAssignments,
    transactions: state.transactions.map(t => gone(t.categoryId) ? { ...t, categoryId: undefined } : t),
    billReminders: state.billReminders.map(r => gone(r.categoryId) ? { ...r, categoryId: undefined } : r),
    accounts: state.accounts.map(a => gone(a.linkedCategoryId) ? { ...a, linkedCategoryId: undefined } : a),
  };
}

// Optional fields the server stores as NULL. JSON drops `undefined`, so a field
// cleared locally has to be sent as an explicit null or the server keeps the
// old value and the change comes back undone on the next load.
const NULLABLE_FIELDS = {
  account: ['interestRate', 'monthlyPayment', 'originalBalance', 'loanStartDate', 'linkedCategoryId'],
  trackingAccount: ['notes'],
  category: ['goal', 'linkedAccountId'],
  transaction: ['categoryId', 'memo', 'autoGeneratedById'],
  billReminder: ['dueDateOverride', 'categoryId', 'accountId', 'lastPaidDate', 'notes'],
} as const;

function withClearedAsNull(updates: object, nullable: readonly string[]): Record<string, unknown> {
  const wire: Record<string, unknown> = { ...updates };
  for (const key of nullable) {
    if (key in wire && wire[key] === undefined) wire[key] = null;
  }
  return wire;
}

